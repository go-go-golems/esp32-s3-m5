static const char* emu_state_name(EmulationState s) {
    switch (s) {
        case EmulationState::None: return "none";
        case EmulationState::Off: return "off";
        case EmulationState::Idle: return "idle";
        case EmulationState::Ready: return "ready";
        case EmulationState::Active: return "active";
        case EmulationState::Halt: return "halt";
        default: return "unknown";
    }
}

extern "C" void app_main(void) {
    printf("smoke emulation: remove physical tag, then scan with phone\n");
    i2c_master_bus_handle_t bus = make_bus();

    Engine engine;
    EngineConfig cfg{};
    cfg.bus = bus;
    cfg.mode = Mode::EmulationNtag213;
    cfg.emulation_profile.family = TagFamily::Ntag21x;
    cfg.emulation_profile.uid = {0x99, 0x88, 0x77, 0x66, 0x55, 0x44, 0x33, 0, 0, 0};
    cfg.emulation_profile.uid_length = 7;
    cfg.emulation_profile.memory.assign(std::begin(NTAG213_MEMORY), std::end(NTAG213_MEMORY));

    auto begin = engine.begin(cfg);
    printf("smoke begin ok=%u state=%s\n", begin.ok() ? 1u : 0u,
           lifecycle_state_name(engine.state()));

    EmulationState last = EmulationState::None;
    for (;;) {
        EmulationState s = engine.update_emulation();
        if (s != last) {
            printf("smoke emu state=%s\n", emu_state_name(s));
            last = s;
        }
        vTaskDelay(pdMS_TO_TICKS(1));
    }
}
