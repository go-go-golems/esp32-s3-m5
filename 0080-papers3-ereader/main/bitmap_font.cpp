static const uint8_t* GetGlyph(char c)
{
    // Map lowercase to uppercase
    if (c >= 'a' && c <= 'z') c = c - 'a' + 'A';

    if (c < 0x20 || c > 0x60) {
        // Out of range: return space
        return kFont5x7[0];
    }
    return kFont5x7[c - 0x20];
}

void DrawBitmapText(M5GFX& display, const char* text, int x, int y,
                    int size, uint32_t color, int max_chars)
{
    if (!text) return;
    int len = static_cast<int>(std::strlen(text));
    if (max_chars >= 0 && len > max_chars) len = max_chars;
    if (size < 1) size = 1;

    for (int i = 0; i < len; ++i) {
        const uint8_t* bm = GetGlyph(text[i]);
        int gx = x + i * kGlyphW * size;
        for (int row = 0; row < 7; ++row) {
            for (int col = 0; col < 5; ++col) {
                if (bm[row] & (1 << (4 - col))) {
                    if (size == 1) {
                        display.drawPixel(gx + col, y + row, color);
                    } else {
                        display.fillRect(gx + col * size, y + row * size, size, size, color);
                    }
                }
            }
        }
    }
}

int MeasureBitmapText(const char* text, int size)
{
    if (!text) return 0;
    return static_cast<int>(std::strlen(text)) * kGlyphW * std::max(1, size);
}

